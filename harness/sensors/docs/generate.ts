// Writes the generated part of the as-built documents (`pnpm docs:generate`): the package list, the
// dependency graph between packages, and the exports of each package. The output depends only on the
// code, so running it twice gives the same files.

import { type SpawnSyncReturns, spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { pathToFileURL } from "node:url";
import { AS_BUILT } from "./pages.ts";

const GENERATED = `${AS_BUILT}/generated`;
const NOTICE = "> Generated by `pnpm docs:generate`. Do not edit.";
const PACKAGE_DIRECTORY = "^(memex/(packages|providers|apps)|factory/validation)/[^/]+";

type WorkspacePackage = { name: string; directory: string };

// pnpm is a .cmd file on Windows, which needs a shell; the command line is fixed.
const PNPM_LS = "pnpm ls --recursive --depth -1 --json";

const output = (result: SpawnSyncReturns<string>, command: string): string => {
  if (result.status !== 0) throw new Error(`${command} failed:\n${result.stderr}`);
  return result.stdout;
};

const workspacePackages = (root: string): WorkspacePackage[] =>
  (
    JSON.parse(
      output(spawnSync(PNPM_LS, { cwd: root, encoding: "utf8", shell: true }), PNPM_LS),
    ) as {
      name: string;
      path: string;
    }[]
  )
    .map(({ name, path }) => ({ name, directory: relative(root, path).replaceAll("\\", "/") }))
    .filter(({ directory }) => directory !== "")
    .sort((a, b) => a.directory.localeCompare(b.directory));

const page = (title: string, lines: string[]): string =>
  [`# ${title}`, "", NOTICE, "", ...lines, ""].join("\n");

const packageList = (packages: WorkspacePackage[]): string =>
  page("Packages", [
    "| Package | Directory |",
    "|---|---|",
    ...packages.map(({ name, directory }) => `| \`${name}\` | \`${directory}/\` |`),
  ]);

const dependencyGraph = (root: string): string => {
  const depcruise = join(root, "node_modules/dependency-cruiser/bin/dependency-cruiser.mjs");
  const args = [
    depcruise,
    "memex",
    "factory/validation",
    "--include-only",
    "^(memex|factory/validation)/",
    "--collapse",
    PACKAGE_DIRECTORY,
    "--output-type",
    "mermaid",
  ];
  const graph = output(
    spawnSync(process.execPath, args, { cwd: root, encoding: "utf8" }),
    "depcruise",
  );
  return page("Dependency graph", [
    "Dependencies between the packages.",
    "",
    "```mermaid",
    graph.trim(),
    "```",
  ]);
};

const exportsOf = async (root: string, { directory }: WorkspacePackage): Promise<string[]> => {
  const manifest = JSON.parse(readFileSync(join(root, directory, "package.json"), "utf8")) as {
    exports?: Record<string, string>;
  };
  const entry = manifest.exports?.["."];
  if (entry === undefined) return [];
  const module = (await import(pathToFileURL(join(root, directory, entry)).href)) as Record<
    string,
    unknown
  >;
  return Object.keys(module).sort();
};

const exportList = async (root: string, packages: WorkspacePackage[]): Promise<string> => {
  const sections = await Promise.all(
    packages.map(async (workspacePackage) => {
      const names = await exportsOf(root, workspacePackage);
      const list = names.length === 0 ? ["None."] : names.map((name) => `- \`${name}\``);
      return [`## ${workspacePackage.name}`, "", ...list, ""];
    }),
  );
  const lines = [
    "The runtime exports of the entry point of each package. Type-only exports are not listed.",
    "",
  ];
  return page("Exports", [...lines, ...sections.flat()].slice(0, -1));
};

export const generate = async (root: string): Promise<string[]> => {
  const packages = workspacePackages(root);
  const files: Record<string, string> = {
    "packages.md": packageList(packages),
    "dependency-graph.md": dependencyGraph(root),
    "exports.md": await exportList(root, packages),
  };
  mkdirSync(join(root, GENERATED), { recursive: true });
  for (const [name, content] of Object.entries(files))
    writeFileSync(join(root, GENERATED, name), content);
  return Object.keys(files).map((name) => `${GENERATED}/${name}`);
};
